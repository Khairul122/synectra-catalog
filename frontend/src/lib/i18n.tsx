export type Locale = 'id' | 'en';
const MESSAGES: Record<Locale, Record<MessageKey, string>> = { id, en };
const STORAGE_KEY = 'synectra-locale';
const listeners = new Set<() => void>();
// Session fallback when localStorage is blocked, so switching still works.
let memoryLocale: Locale | null = null;

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  const text = MESSAGES[locale][key];
  return vars ? text.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`)) : text;
}

function readLocale(): Locale {
  if (memoryLocale) return memoryLocale;
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'id' || stored === 'en') return stored;
  } catch {
    // storage blocked: fall through to browser language
  }
  return navigator.language?.toLowerCase().startsWith('id') ? 'id' : 'en';
}

function subscribe(cb: () => void) {
  listeners.add(cb);
  const onStorage = (e: StorageEvent) => e.key === STORAGE_KEY && cb();
  window.addEventListener('storage', onStorage);
  return () => {
    listeners.delete(cb);
    window.removeEventListener('storage', onStorage);
  };
}

interface I18nValue {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: MessageKey, vars?: Record<string, string | number>) => string;
  /** BCP 47 tag for Intl formatting. */
  intl: string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  // Server render is Indonesian (the store's home market); the client switches after hydration.
  const locale = useSyncExternalStore(subscribe, readLocale, () => 'id' as Locale);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = useCallback((l: Locale) => {
    memoryLocale = l;
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      // not persisted; memoryLocale keeps it for this session
    }
    listeners.forEach((cb) => cb());
  }, []);

  const t = useCallback((key: MessageKey, vars?: Record<string, string | number>) => translate(locale, key, vars), [locale]);

  return <I18nContext.Provider value={{ locale, setLocale, t, intl: locale === 'id' ? 'id-ID' : 'en-US' }}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
